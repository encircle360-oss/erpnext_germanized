def bench(tmp_path: Path) -> Path:
	"""A bench like bench init leaves it: three apps, built assets, Socket.IO and build tools."""
	root = tmp_path / "frappe-bench"
	frappe = root / "apps" / "frappe"
	write(frappe / "socketio.js", 'const { realtime } = require("./realtime");\nrequire("fs");\n')
	write(
		frappe / "realtime" / "index.js",
		'const io = require("socket.io");\nconst c = require("cookie");\nconst u = require("../node_utils");\n',
	)
	write(frappe / "node_utils.js", 'const redis = require("@redis/client");\n')
	write(
		frappe / "frappe" / "public" / "js" / "print.js",
		'load("/assets/frappe/node_modules/qz-tray/qz-tray.js");',
	)
	package(frappe, "socket.io", {"engine.io": "^6"})
	package(frappe, "engine.io")
	package(frappe, "cookie")
	package(frappe, "@redis/client")
	package(frappe, "qz-tray")
	package(frappe, "esbuild")
	package(frappe, "loader-utils")
	package(frappe, "@babel/core")
	(frappe / "node_modules" / ".bin").mkdir()
	(frappe / "node_modules" / ".bin" / "esbuild").symlink_to("../esbuild")
	write(frappe / "node_modules" / ".yarn-integrity", "{}")
	package(frappe / "studio" / "frontend", "vite")
	package(frappe / ".git" / "hooks", "never-scanned")
	(frappe / "frappe" / "public" / "node_modules").symlink_to(frappe / "node_modules")

	erpnext = root / "apps" / "erpnext"
	write(erpnext / "erpnext" / "public" / "js" / "bom.js", "")
	write(
		erpnext / "erpnext" / "public" / "dist" / "js" / "bom.bundle.js",
		'var b="/assets/erpnext/node_modules/occt-import-js/dist/";',
	)
	write(
		erpnext / "erpnext" / "public" / "dist" / "js" / "bom.bundle.js.map",
		'"assets/erpnext/node_modules/rollup/x.js"',
	)
	package(erpnext, "occt-import-js")
	package(erpnext, "rollup")
	package(erpnext / "islands", "vue")
	(erpnext / "erpnext" / "public" / "node_modules").symlink_to(erpnext / "node_modules")

	hrms = root / "apps" / "hrms"
	package(hrms, "frappe-ui")
	(hrms / "hrms" / "public").mkdir(parents=True)
	(hrms / "hrms" / "public" / "node_modules").symlink_to(hrms / "node_modules")
	package(hrms / "frontend", "@babel/traverse")
	write(hrms / "README.md", "not an app directory with code")

	write(root / "apps" / "apps.txt", "frappe\nerpnext\nhrms\n")
	# bench build links sites/assets/<app> to the public directory of the app, where the bundles are built.
	assets = root / "sites" / "assets"
	write(assets / "assets.json", '{"bom.bundle.js": "/assets/erpnext/dist/js/bom.bundle.js"}')
	for app in ("frappe", "erpnext", "hrms"):
		(assets / app).symlink_to(root / "apps" / app / app / "public")
	return root


def test_prune_keeps_what_runs_and_removes_the_build_tools(tmp_path):
	root = bench(tmp_path)
	apps = root / "apps"
	report = prune(root)

	assert names(apps / "frappe") == {"socket.io", "engine.io", "cookie", "@redis/client", "qz-tray"}
	assert not (apps / "frappe" / "node_modules" / ".yarn-integrity").exists()
	assert not (apps / "frappe" / "node_modules" / ".bin").exists()
	assert not (apps / "frappe" / "node_modules" / "@babel").exists()
	assert (apps / "frappe" / "frappe" / "public" / "node_modules").is_symlink()
	assert not (apps / "frappe" / "studio" / "frontend" / "node_modules").exists()
	assert (apps / "frappe" / ".git" / "hooks" / "node_modules").exists()

	assert names(apps / "erpnext") == {"occt-import-js"}
	assert not (apps / "erpnext" / "islands" / "node_modules").exists()

	assert not (apps / "hrms" / "node_modules").exists()
	assert not (apps / "hrms" / "frontend" / "node_modules").exists()
	assert not (apps / "hrms" / "hrms" / "public" / "node_modules").is_symlink()
	assert not (root / "sites" / "assets" / "hrms" / "node_modules").exists()
	assert (root / "sites" / "assets" / "frappe" / "node_modules" / "qz-tray" / "package.json").is_file()
	assert (root / "sites" / "assets" / "erpnext" / "node_modules" / "occt-import-js").is_dir()

	assert report == [
		"erpnext: kept 1 of 2 packages in node_modules, removed 1 node_modules of sub projects",
		"frappe: kept 5 of 8 packages in node_modules, removed 1 node_modules of sub projects",
		"hrms: kept 0 of 1 packages in node_modules, removed 1 node_modules of sub projects",
	]


