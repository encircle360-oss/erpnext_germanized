def package(directory: Path, name: str, dependencies=None, **fields) -> Path:
	"""A package directory with a package.json under directory/node_modules."""
	path = directory / "node_modules" / name
	path.mkdir(parents=True)
	manifest = {"name": name, "version": "1.0.0", **fields}
	if dependencies is not None:
		manifest["dependencies"] = dependencies
	(path / "package.json").write_text(json.dumps(manifest), encoding="utf-8")
	return path


def write(path: Path, text: str) -> Path:
	path.parent.mkdir(parents=True, exist_ok=True)
	path.write_text(text, encoding="utf-8")
	return path


def names(directory: Path) -> set[str]:
	"""The packages left in directory/node_modules, scoped ones as @scope/name."""
	found = set()
	root = directory / "node_modules"
	for entry in root.iterdir():
		if entry.name.startswith("@"):
			found |= {f"{entry.name}/{child.name}" for child in entry.iterdir()}
		elif not entry.name.startswith("."):
			found.add(entry.name)
	return found


