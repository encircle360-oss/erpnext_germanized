"""Prune the Node.js packages of a bench down to what still runs after the build.

`bench init` installs the Node.js dependencies of every app, and of the frontends inside the apps, and builds
the assets with them. After the build the bench needs only two kinds of package:

- the packages the browser loads at run time from `/assets/<app>/node_modules/<package>`, a path that the built
  assets and the app sources name literally, such as qz-tray for printing or occt-import-js for 3D models, and
- the packages that Frappe's Socket.IO server requires: `socketio.js`, what it loads by relative path, and the
  `realtime` directory of every app, from which it loads `realtime/handlers.js` at run time, and
- what saving a Website Theme needs: Frappe compiles the theme with `node generate_bootstrap_theme.js`, which
  requires sass, and its SCSS imports packages such as Bootstrap from the node_modules of the apps,

each with every package it depends on. Everything else is a build tool, the node_modules of the frontends inside
the apps among it, and goes; with it go the compilers, bundlers and esbuild binaries that vulnerability scanners
report although nothing loads them. The bench cannot run `bench build` afterwards, and Frappe Studio cannot
build the bundle of a published app; a new app means a new image anyway.
"""

import json
import os
import re
import shutil
from collections.abc import Iterable, Iterator
from pathlib import Path

# The Node.js entry points of every app, relative to the app: Frappe's Socket.IO server socketio.js, the Website
# Theme compiler generate_bootstrap_theme.js, which Frappe runs whenever a theme is saved, and the realtime
# directory, from which the Socket.IO server loads <app>/realtime/handlers.js of every app by a computed path.
ENTRY_FILES = ("socketio.js", "generate_bootstrap_theme.js")
ENTRY_DIRECTORIES = ("realtime",)
# The files whose text can name a package: sources, templates and built assets, but no source maps, which name
# the packages a bundle was built from.
SCANNED_SUFFIXES = frozenset({".js", ".mjs", ".cjs", ".ts", ".vue", ".css", ".html", ".py", ".json"})
SKIPPED_DIRECTORIES = frozenset({"node_modules", ".git"})

_ASSET_REFERENCE = re.compile(r"assets/(?P<app>[a-z0-9_]+)/node_modules/(?P<package>(?:@[\w.-]+/)?[\w.-]+)")
_IMPORT = re.compile(
	r"""(?:\brequire\s*\(\s*|\bimport\s*\(\s*|\bfrom\s+|\bimport\s+)(?P<quote>["'])(?P<specifier>[^"'\s]+)(?P=quote)"""
)
# An SCSS @import, @use or @forward, which may name several files: @import "a", "b";
_STYLE_RULE = re.compile(r"@(?:import|use|forward)\s+(?P<arguments>[^;]+)")
_QUOTED = re.compile(r"""(?P<quote>["'])(?P<specifier>[^"']+)(?P=quote)""")


def package_name(specifier: str) -> str | None:
	"""The package a require or import names, None for a relative or absolute path and for a Node.js builtin."""
	if specifier.startswith((".", "/", "node:")):
		return None
	parts = specifier.split("/")
	if specifier.startswith("@"):
		return "/".join(parts[:2]) if len(parts) > 1 else None
	return parts[0]


def specifiers(text: str) -> set[str]:
	"""What a JavaScript text requires or imports, statically or dynamically, as literally written."""
	return {match["specifier"] for match in _IMPORT.finditer(text)}


def requires(text: str) -> set[str]:
	"""The packages a JavaScript text requires or imports."""
	found = (package_name(specifier) for specifier in specifiers(text))
	return {name for name in found if name}


def asset_references(text: str) -> set[tuple[str, str]]:
	"""The (app, package) of every path assets/<app>/node_modules/<package> in a text."""
	return {(match["app"], match["package"]) for match in _ASSET_REFERENCE.finditer(text)}


def resolve(name: str, start: Path, root: Path) -> Path | None:
	"""The directory of package name as Node.js finds it from start, looking no higher than root."""
	directory = start
	while True:
		if directory.name != "node_modules":
			candidate = directory / "node_modules" / name
			if (candidate / "package.json").is_file():
				return candidate
		if directory == root or directory == directory.parent:
			return None
		directory = directory.parent


def _label(package: Path) -> str:
	return f"{package.parent.name}/{package.name}" if package.parent.name.startswith("@") else package.name


def runtime_packages(app: Path, roots: Iterable[tuple[Path, str]]) -> set[Path]:
	"""The directories of the packages each (start, name) of roots resolves to, with all they depend on.

	A root that resolves to nothing is a Node.js builtin or a package the app does not install, and is skipped.
	A missing optional or peer dependency is skipped as Node.js skips it; a missing regular dependency means the
	installation is broken, which is an error.
	"""
	pending = [found for start, name in roots if (found := resolve(name, start, app))]
	kept: set[Path] = set()
	while pending:
		package = pending.pop()
		if package in kept:
			continue
		kept.add(package)
		manifest = json.loads((package / "package.json").read_text(encoding="utf-8"))
		optional = {**manifest.get("optionalDependencies", {}), **manifest.get("peerDependencies", {})}
		for name in {**manifest.get("dependencies", {}), **optional}:
			found = resolve(name, package, app)
			if found:
				pending.append(found)
			elif name not in optional:
				raise ValueError(f"{_label(package)} needs {name}, which is not installed")
	return kept


def _local_module(specifier: str, importer: Path, app: Path) -> Path | None:
	"""The file a relative require of importer loads, as Node.js completes it, if it lies inside app."""
	base = Path(os.path.normpath(importer.parent / specifier))
	for candidate in (base, base.with_name(base.name + ".js"), base / "index.js"):
		if candidate.is_file():
			return candidate if candidate.is_relative_to(app) else None
	return None


def node_roots(app: Path) -> list[tuple[Path, str]]:
	"""(directory, package) for every package the entry points of app require, following relative requires."""
	pending = [app / name for name in ENTRY_FILES if (app / name).is_file()]
	pending += [
		directory / name
		for entry in ENTRY_DIRECTORIES
		for directory, _, files in _walk(app / entry)
		for name in files
	]
	pending = [file for file in pending if file.suffix == ".js"]
	seen, roots = set(pending), []
	while pending:
		file = pending.pop()
		for specifier in specifiers(file.read_text(encoding="utf-8")):
			if specifier.startswith("."):
				local = _local_module(specifier, file, app)
				if local and local not in seen:
					seen.add(local)
					pending.append(local)
			elif name := package_name(specifier):
				roots.append((file.parent, name))
	return roots


def style_roots(app: Path) -> list[tuple[Path, str]]:
	"""(app, package) for every package the SCSS of app/<app>/public imports, as sass finds it in app/node_modules.

	A Website Theme imports <app>/public/scss/website of every app, so only the SCSS below the public directory
	of the app counts; the frontends inside an app style themselves from node_modules of their own. Sass resolves
	an import against every app and every node_modules of the bench, so a bare name may as well be a partial next
	to the file or a path into an app, such as "variables" or "frappe/public/scss/website"; such a name resolves
	to no package and runtime_packages skips it. A leading ~ is webpack's mark for node_modules.
	"""
	roots = []
	for directory, _, files in _walk(app / app.name / "public"):
		for name in files:
			if not name.endswith(".scss"):
				continue
			text = (directory / name).read_text(encoding="utf-8", errors="ignore")
			for rule in _STYLE_RULE.finditer(text):
				for match in _QUOTED.finditer(rule["arguments"]):
					specifier = match["specifier"].removeprefix("~")
					if "://" not in specifier and (package := package_name(specifier)):
						roots.append((app, package))
	return roots


def _walk(top: Path) -> Iterator[tuple[Path, list[str], list[str]]]:
	"""os.walk without node_modules and .git, and without following links."""
	for directory, subdirectories, files in os.walk(top):
		subdirectories[:] = [name for name in subdirectories if name not in SKIPPED_DIRECTORIES]
		yield Path(directory), subdirectories, files


def _texts(top: Path) -> Iterator[str]:
	for directory, _, files in _walk(top):
		for name in files:
			if Path(name).suffix in SCANNED_SUFFIXES:
				yield (directory / name).read_text(encoding="utf-8", errors="ignore")


def _nested_node_modules(app: Path) -> list[Path]:
	"""The outermost node_modules directories below app, apart from app/node_modules, outside .git.

	A link named node_modules, such as public/node_modules that bench build points at app/node_modules, is an
	alias and no directory of its own.
	"""
	found = []
	for directory, subdirectories, _ in os.walk(app):
		subdirectories[:] = [name for name in subdirectories if name != ".git"]
		if "node_modules" in subdirectories:
			subdirectories.remove("node_modules")
			path = Path(directory) / "node_modules"
			if path != app / "node_modules" and not path.is_symlink():
				found.append(path)
	return found


def _unlink_dangling(top: Path) -> None:
	"""Remove every link named node_modules below top whose target is gone."""
	for directory, subdirectories, files in os.walk(top):
		for name in (*subdirectories, *files):
			path = Path(directory) / name
			if name == "node_modules" and path.is_symlink() and not path.exists():
				path.unlink()
		subdirectories[:] = [name for name in subdirectories if name not in SKIPPED_DIRECTORIES]


def _entries(node_modules: Path) -> Iterator[Path]:
	"""The packages in a node_modules directory, those of a scope included."""
	for entry in sorted(node_modules.iterdir()):
		if entry.name.startswith("@") and entry.is_dir() and not entry.is_symlink():
			yield from sorted(entry.iterdir())
		elif not entry.name.startswith("."):
			yield entry


def _remove(path: Path) -> None:
	if path.is_symlink() or path.is_file():
		path.unlink()
	else:
		shutil.rmtree(path)


def _prune_directory(node_modules: Path, kept: set[Path]) -> None:
	"""Remove what kept does not name from node_modules, and every dot entry: .bin, caches and build output.

	A link is never followed: a linked package that is not kept is unlinked, and the node_modules of a kept
	package is left alone when either is a link, since its target may lie outside the bench.
	"""
	for package in list(_entries(node_modules)):
		inner = package / "node_modules"
		if package not in kept:
			_remove(package)
		elif inner.is_dir() and not package.is_symlink() and not inner.is_symlink():
			_prune_directory(inner, kept)
	for entry in node_modules.iterdir():
		if entry.name.startswith(".") or (
			entry.name.startswith("@") and entry.is_dir() and not any(entry.iterdir())
		):
			_remove(entry)


def prune(bench: Path) -> list[str]:
	"""Remove every Node.js package of the apps of bench that nothing loads at run time; one line per app."""
	apps = bench / "apps"
	if not apps.is_dir():
		raise ValueError(f"{bench} has no apps directory")
	references: set[tuple[str, str]] = set()
	for text in (*_texts(apps), *_texts(bench / "sites" / "assets")):
		references |= asset_references(text)

	report = []
	for app in sorted(path for path in apps.iterdir() if path.is_dir()):
		top, nested = app / "node_modules", _nested_node_modules(app)
		# Deleting follows no link out of the bench: an app or a node_modules that is a link is refused.
		for path in (app, top):
			if path.is_symlink():
				raise ValueError(
					f"{path.relative_to(bench)} is a link; prune-node-modules only prunes the bench itself"
				)
		if not top.is_dir() and not nested:
			continue
		roots = [(app, package) for name, package in references if name == app.name]
		kept = runtime_packages(app, roots + node_roots(app) + style_roots(app))
		packages = list(_entries(top)) if top.is_dir() else []
		removed = 0
		for path in nested:
			if any(package.is_relative_to(path) for package in kept):
				_prune_directory(path, kept)
			else:
				_remove(path)
				removed += 1
		if any(package.is_relative_to(top) for package in kept):
			_prune_directory(top, kept)
		elif top.is_dir():
			_remove(top)
		for package in sorted(kept):
			if not (package / "package.json").is_file():
				raise ValueError(f"{app.name}: {_label(package)} is gone after pruning")
		report.append(
			f"{app.name}: kept {sum(path in kept for path in packages)} of {len(packages)} packages in "
			f"node_modules, removed {removed} node_modules of sub projects"
		)
	_unlink_dangling(apps)
	_unlink_dangling(bench / "sites" / "assets")
	return report
